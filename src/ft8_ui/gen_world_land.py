#
#  Generates world_land.c (land outlines, country borders and the
#  state/province lines of large countries for the FT8 map) from the
#  public-domain Natural Earth data:
#
#    NE=https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson
#    curl -LO $NE/ne_10m_land.geojson
#    curl -LO $NE/ne_50m_admin_0_boundary_lines_land.geojson
#    curl -LO $NE/ne_50m_admin_1_states_provinces_lines.geojson
#    python3 gen_world_land.py ne_10m_land.geojson ne_50m_admin_0_boundary_lines_land.geojson \
#        ne_50m_admin_1_states_provinces_lines.geojson > world_land.c
#
#  Lines are simplified (Douglas-Peucker) and stored as 0.1 degree int16.
#  The 1:10m land simplified to 0.05 degree stays smooth up to the map's
#  maximum zoom (~1.4 px error at 12x) and keeps islands such as Taiwan,
#  Hawaii, Okinawa or Jeju that the 1:110m data or a larger MIN_AREA drop.
#  Borders and state lines come from the 1:50m data.

import json
import sys

TOLERANCE = 0.05    # degrees
BORDER_TOLERANCE = 0.05
ADMIN1_TOLERANCE = 0.1
MIN_AREA  = 0.05    # square degrees, smaller islands are dropped


def simplify(pts, tol):
    if len(pts) < 3:
        return pts
    ax, ay = pts[0]
    bx, by = pts[-1]
    dx, dy = bx - ax, by - ay
    norm = (dx * dx + dy * dy) ** 0.5
    best, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        px, py = pts[i]
        if norm == 0:
            d = ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
        else:
            d = abs(dy * px - dx * py + bx * ay - by * ax) / norm
        if d > best:
            best, idx = d, i
    if best <= tol:
        return [pts[0], pts[-1]]
    return simplify(pts[:idx + 1], tol)[:-1] + simplify(pts[idx:], tol)


def area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2


def to_points(line):
    pts = []
    for lon, lat in line:
        p = (round(lon * 10), round(max(lat, -89.9) * 10))
        if not pts or pts[-1] != p:
            pts.append(p)
    return pts


def write_lines(out, name, lines):
    total = sum(len(r) for r in lines)
    out.write("const int16_t %s_pts[%d][2] = {\n" % (name, total))
    for r in lines:
        line = ""
        for lon, lat in r:
            item = "{%d,%d}," % (lon, lat)
            if len(line) + len(item) > 96:
                out.write("    " + line + "\n")
                line = ""
            line += item
        out.write("    " + line + "\n")
    out.write("};\n\n")
    out.write("const uint16_t %s_len[%d] = {\n" % (name, len(lines)))
    lens = [str(len(r)) for r in lines]
    for i in range(0, len(lens), 16):
        out.write("    " + ",".join(lens[i:i + 16]) + ",\n")
    out.write("};\n\n")
    out.write("const uint16_t %s_count = %d;\n\n" % (name, len(lines)))


def read_lines(path, tol):
    res = []
    for feature in json.load(open(path))["features"]:
        geom = feature["geometry"]
        if geom is None:
            continue
        lines = geom["coordinates"] if geom["type"] == "MultiLineString" else [geom["coordinates"]]
        for line in lines:
            pts = to_points(simplify(line, tol))
            if len(pts) >= 2:
                res.append(pts)
    return res


def main():
    rings = []
    for feature in json.load(open(sys.argv[1]))["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            for ring in poly:
                if area(ring) < MIN_AREA:
                    continue
                pts = to_points(simplify(ring, TOLERANCE))
                if len(pts) >= 4:
                    rings.append(pts)

    borders = read_lines(sys.argv[2], BORDER_TOLERANCE)
    admin1 = read_lines(sys.argv[3], ADMIN1_TOLERANCE)

    out = sys.stdout
    out.write("/* Generated by gen_world_land.py from Natural Earth 1:10m/1:50m data (public domain). */\n\n")
    out.write('#include "world_land.h"\n\n')
    write_lines(out, "world_land", rings)
    write_lines(out, "world_border", borders)
    write_lines(out, "world_admin1", admin1)


if __name__ == "__main__":
    main()
